import { createClient } from '@supabase/supabase-js';
import dotenv from 'dotenv';
dotenv.config();
const supabase = createClient(process.env.VITE_SUPABASE_URL, process.env.VITE_SUPABASE_ANON_KEY);
async function run() {
  const { data, error } = await supabase.rpc('exec_sql', { query: "ALTER TABLE inventory ADD COLUMN is_group BOOLEAN DEFAULT false;" });
  console.log(error);
}
run();
